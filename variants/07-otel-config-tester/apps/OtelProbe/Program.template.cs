// Called by the order flow for every line (in parallel), and callable directly.
app.MapGet("/api/pricing/{sku}", async (string sku, ShopDb db) =>
{
    Activity.Current?.SetTag("shop.sku", sku);
    var p = await db.Products.AsNoTracking()
        .Where(x => x.Sku == sku)
        .Select(x => new { x.Sku, x.Price, x.Category })
        .FirstOrDefaultAsync();
    if (p is null) return Results.NotFound();

    using var rules = Probe.Source.StartActivity("Apply discount rules");
    await Task.Delay(Random.Shared.Next(5, 30)); // some visible duration
    var discount = p.Category == "tools" ? 0.10 : 0.0;
    rules?.SetTag("shop.category", p.Category);
    rules?.SetTag("shop.discount", discount);
    rules?.AddEvent(new ActivityEvent("discount.evaluated", tags: new ActivityTagsCollection
    {
        ["rule"] = p.Category == "tools" ? "tools-10-percent" : "none",
    }));
    return Results.Ok(new PriceResponse(p.Sku, Math.Round(p.Price * (1 - discount), 2), discount));
});

app.MapPost("/api/orders", async (OrderRequest req, ShopDb db, IHttpClientFactory http) =>
{
    var span = Activity.Current;
    span?.SetTag("shop.customer_id", req.CustomerId);
    span?.SetTag("shop.line_count", req.Lines.Count);

    // 1. Validate: the customer exists and the order is well-formed.
    Customer? customer;
    using (var validate = Probe.Source.StartActivity("Validate order"))
    {
        customer = await db.Customers.AsNoTracking().FirstOrDefaultAsync(c => c.Id == req.CustomerId);
        if (customer is null || req.Lines.Count == 0 || req.Lines.Any(l => l.Quantity <= 0))
        {
            var reason = customer is null ? "unknown_customer" : "invalid_lines";
            validate?.AddEvent(new ActivityEvent("validation.failed", tags: new ActivityTagsCollection { ["reason"] = reason }));
            span?.SetTag("shop.outcome", reason);
            return customer is null ? Results.NotFound(new { error = reason }) : Results.BadRequest(new { error = reason });
        }
        validate?.AddEvent(new ActivityEvent("validation.passed"));
        span?.SetTag("shop.customer_tier", customer.Tier);
    }

    // 2. Price every line through the pricing endpoint, all lines in parallel.
    var self = http.CreateClient("self");
    var skus = req.Lines.Select(l => l.Sku).Distinct().ToList();
    var priced = await Task.WhenAll(skus.Select(async sku =>
    {
        using var resp = await self.GetAsync($"/api/pricing/{Uri.EscapeDataString(sku)}");
        return resp.IsSuccessStatusCode ? await resp.Content.ReadFromJsonAsync<PriceResponse>() : null;
    }));
    if (priced.Any(p => p is null))
    {
        span?.SetTag("shop.outcome", "unknown_sku");
        return Results.BadRequest(new { error = "unknown_sku" });
    }
    var prices = priced.ToDictionary(p => p!.Sku, p => p!.UnitPrice);

    // 3. Reserve stock and store the order, in one transaction.
    var orderId = Guid.NewGuid().ToString("N")[..12];
    span?.SetTag("shop.order_id", orderId);
    double total;
    using (var reserve = Probe.Source.StartActivity("Reserve stock"))
    {
        await using var tx = await db.Database.BeginTransactionAsync();
        foreach (var line in req.Lines)
        {
            var qty = line.Quantity;
            var updated = await db.Products
                .Where(p => p.Sku == line.Sku && p.Stock >= qty)
                .ExecuteUpdateAsync(s => s.SetProperty(p => p.Stock, p => p.Stock - qty));
            if (updated == 0)
            {
                await tx.RollbackAsync();
                reserve?.AddEvent(new ActivityEvent("stock.insufficient", tags: new ActivityTagsCollection
                {
                    ["sku"] = line.Sku,
                    ["requested"] = qty,
                }));
                span?.SetTag("shop.outcome", "insufficient_stock");
                return Results.Conflict(new { error = "insufficient_stock", sku = line.Sku });
            }
        }

        total = Math.Round(req.Lines.Sum(l => prices[l.Sku] * l.Quantity), 2);
        db.Orders.Add(new Order
        {
            Id = orderId,
            CustomerId = req.CustomerId,
            CreatedAtUtc = DateTime.UtcNow,
            Total = total,
            Status = "placed",
            Lines = req.Lines.Select(l => new OrderLine { Sku = l.Sku, Quantity = l.Quantity, UnitPrice = prices[l.Sku] }).ToList(),
        });
        await db.SaveChangesAsync();
        await tx.CommitAsync();
        reserve?.AddEvent(new ActivityEvent("stock.reserved", tags: new ActivityTagsCollection { ["lines"] = req.Lines.Count }));
    }
    span?.SetTag("shop.order_total", total);

    // 4. Notify. A third level: CLIENT -> SERVER -> db INSERT.
    using (var notify = await self.PostAsJsonAsync("/api/notifications", new NotificationRequest(orderId, "email")))
    {
        span?.SetTag("shop.notified", notify.IsSuccessStatusCode);
    }

    span?.SetTag("shop.outcome", "placed");
    return Results.Created($"/api/orders/{orderId}", new { orderId, total });
});

