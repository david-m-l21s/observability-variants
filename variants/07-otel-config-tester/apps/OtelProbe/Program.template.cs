// For the test page (wwwroot/index.html): tell the caller which trace this
// request belongs to, and whether its span is recorded. Recorded=false means
// the span exists in the process but will not be exported (dropped by a
// Filter, or not sampled). No header at all means there is no server activity:
// ASP.NET Core instrumentation is off. Adds nothing to the telemetry itself.
app.Use(async (ctx, next) =>
{
    if (Activity.Current is { } a)
    {
        ctx.Response.Headers["X-Trace-Id"] = a.TraceId.ToHexString();
        ctx.Response.Headers["X-Trace-Recorded"] = a.Recorded ? "true" : "false";
    }
    await next();
});

