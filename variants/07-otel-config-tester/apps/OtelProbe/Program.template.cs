// --- span size ---------------------------------------------------------------
// Everything the "Span limits" options cap, on purpose and far over the SDK
// defaults: one very long attribute value, many attributes, many events with
// many attributes each, and a custom child span with many links.
//   /api/wide?attrs=200&events=40&links=40&valueLength=20000
app.MapGet("/api/wide", (int? attrs, int? events, int? links, int? valueLength) =>
{
    int nAttrs = Math.Clamp(attrs ?? 200, 0, 1000), nEvents = Math.Clamp(events ?? 40, 0, 1000);
    int nLinks = Math.Clamp(links ?? 40, 0, 1000), len = Math.Clamp(valueLength ?? 20000, 0, 1_000_000);

    static IEnumerable<KeyValuePair<string, object?>> Tags(int n) =>
        Enumerable.Range(0, n).Select(j => new KeyValuePair<string, object?>($"k{j:D2}", j));

    void Fill(Activity? a)
    {
        if (a is null) return;
        a.SetTag("probe.long_value", new string('x', len));
        for (var i = 0; i < nAttrs; i++) a.SetTag($"probe.attr.{i:D3}", $"value-{i}");
        for (var i = 0; i < nEvents; i++)
            a.AddEvent(new ActivityEvent($"probe.event.{i:D3}", tags: new ActivityTagsCollection(Tags(20))));
    }

    var server = Activity.Current;
    Fill(server);

    var linkList = Enumerable.Range(0, nLinks).Select(_ => new ActivityLink(
        new ActivityContext(ActivityTraceId.CreateRandom(), ActivitySpanId.CreateRandom(), ActivityTraceFlags.Recorded),
        new ActivityTagsCollection(Tags(20)))).ToList();
    using (var wide = Probe.Source.StartActivity("Wide span", ActivityKind.Internal,
               parentContext: server?.Context ?? default, links: linkList))
    {
        Fill(wide);
    }

    return Results.Ok(new { attrs = nAttrs, events = nEvents, links = nLinks, valueLength = len });
});

