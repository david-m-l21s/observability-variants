// --- database ----------------------------------------------------------------
// SQLite in a FILE under /tmp (not in-memory, unlike variant 06): the order
// flow, the parallel pricing calls and the background worker write and read
// at the same time. In-memory shared-cache SQLite answers concurrent access
// with "database table is locked" instead of waiting. A file in WAL mode lets
// readers run while one writer writes, and writers wait (busy timeout) instead
// of failing. The file is deleted at startup: every pod starts empty.
var dbPath = builder.Configuration["PROBE_DB_PATH"] ?? Path.Combine(Path.GetTempPath(), "shop.db");
builder.Services.AddDbContext<ShopDb>(o => o.UseSqlite($"Data Source={dbPath};Default Timeout=30"));

builder.Services.AddHttpClient("self", c =>
{
    c.BaseAddress = new Uri(selfUrl);
    c.Timeout = TimeSpan.FromSeconds(15);
});
builder.Services.AddHttpClient("outside", c => c.Timeout = TimeSpan.FromSeconds(5));

// CORS so that OPTIONS preflight requests get a real answer (and a span,
