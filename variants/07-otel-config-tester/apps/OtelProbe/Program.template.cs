// OtelProbe — variant 07-otel-config-tester.
//
// This is a TEMPLATE. scripts/render.mjs replaces the two @@OTEL_...@@ markers
// with the output of the OTel Tracing Configurator (configurator/*.html) and
// writes the result to build/<config>/app/Program.cs. Everything else in this
// file is the same for every configuration, so the only difference between two
// runs is the OpenTelemetry wiring under test.
//
// The app is a small shop. It exists to produce the kinds of spans the
// configurator has options for, and to produce traces that are more than one
// span deep:
//
//   POST /api/orders   the main flow, one trace, typically 12-20 spans:
//     SERVER  POST /api/orders
//       INTERNAL "Validate order"            (custom ActivitySource)
//         CLIENT  SELECT customers           (EF Core)
//       CLIENT  GET /api/pricing/{sku}       (HttpClient, one per line, in PARALLEL)
//         SERVER  GET /api/pricing/{sku}
//           CLIENT  SELECT products          (EF Core)
//           INTERNAL "Apply discount rules"  (custom, with a span event)
//       INTERNAL "Reserve stock"             (custom)
//         CLIENT  UPDATE products            (EF Core, one per line)
//         CLIENT  INSERT orders/order_lines  (EF Core)
//       CLIENT  POST /api/notifications      (HttpClient)
//         SERVER  POST /api/notifications
//           CLIENT  INSERT notifications     (EF Core)
//
//   Plus single-purpose endpoints for filters, exceptions, span limits and
//   outgoing-call filters. The list is in README.md and in scripts/06-probe.sh.
//
//   GET /  is a test page (wwwroot/index.html) with buttons for all of it.
//
// Which spans actually appear depends entirely on the generated configuration.
// For example: without AddEntityFrameworkCoreInstrumentation() there are no
// SELECT/INSERT spans; without the custom source in AddSource(...) there are no
// "Validate order" spans; with AddAspNetCoreInstrumentation() off, every
// outgoing HttpClient call becomes its own root span.
//
// The custom ActivitySource name comes from PROBE_SOURCE. render.mjs sets it to
// the first name in the configuration's "ActivitySource names" list, so the
// custom spans are listened to exactly when the configuration says so.

