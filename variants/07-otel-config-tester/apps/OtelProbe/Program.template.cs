static class Probe
{
    public static ActivitySource Source { get; private set; } = new("OtelProbe");
    public static string RunId { get; private set; } = "";
    public static string ConfigName { get; private set; } = "";

    public static void Init(string sourceName, string runId, string configName)
    {
        Source = new ActivitySource(sourceName);
        RunId = runId;
        ConfigName = configName;
    }
}

// A background job with no HTTP request around it. With the custom source
// listened to, each run is a ROOT span "Stock sync" with db children. Without
// it, the db spans themselves become separate root spans (or nothing, without
// EF instrumentation). Every 30 s; PROBE_WORKER_SECONDS=0 switches it off.
sealed class StockSyncWorker(IServiceScopeFactory scopes, IConfiguration config, ILogger<StockSyncWorker> log) : BackgroundService
{
    protected override async Task ExecuteAsync(CancellationToken stop)
    {
        var seconds = int.TryParse(config["PROBE_WORKER_SECONDS"], out var s) ? s : 30;
        if (seconds <= 0) return;
        await Task.Delay(TimeSpan.FromSeconds(5), stop);
        while (!stop.IsCancellationRequested)
        {
            try
            {
                using var run = Probe.Source.StartActivity("Stock sync", ActivityKind.Internal);
                using var scope = scopes.CreateScope();
                var db = scope.ServiceProvider.GetRequiredService<ShopDb>();
                var low = await db.Products.CountAsync(p => p.Stock < 100, stop);
                var restocked = await db.Products.Where(p => p.Stock < 100)
                    .ExecuteUpdateAsync(u => u.SetProperty(p => p.Stock, p => p.Stock + 500), stop);
                run?.SetTag("shop.low_stock_products", low);
                run?.SetTag("shop.restocked", restocked);
            }
            catch (Exception ex) when (ex is not OperationCanceledException)
            {
                log.LogWarning(ex, "Stock sync failed");
            }
            await Task.Delay(TimeSpan.FromSeconds(seconds), stop);
        }
    }
}

static class Seed
{
    static readonly string[] Categories = ["tools", "garden", "kitchen"];
    static readonly string[] Tiers = ["standard", "standard", "standard", "gold", "platinum"];

    public static void Run(ShopDb db)
    {
        for (var i = 1; i <= 50; i++)
            db.Customers.Add(new Customer { Id = $"C{i:D3}", Name = $"Customer {i}", Tier = Tiers[i % Tiers.Length] });
        for (var i = 1; i <= 30; i++)
            db.Products.Add(new Product
            {
                Sku = $"SKU-{i:D3}",
                Name = $"Product {i}",
                Category = Categories[i % Categories.Length],
                Price = Math.Round(4.99 + i * 3.1, 2),
                Stock = 1000,
            });
        db.SaveChanges();
    }
}

record OrderRequest(string CustomerId, List<OrderLineRequest> Lines);
record OrderLineRequest(string Sku, int Quantity);
record PriceResponse(string Sku, double UnitPrice, double Discount);
record NotificationRequest(string OrderId, string Channel);

// double, not decimal: the SQLite provider cannot ORDER BY or SUM a decimal.
class Customer { public string Id { get; set; } = ""; public string Name { get; set; } = ""; public string Tier { get; set; } = ""; }
class Product
{
    public string Sku { get; set; } = "";
    public string Name { get; set; } = "";
    public string Category { get; set; } = "";
    public double Price { get; set; }
    public int Stock { get; set; }
}
class Order
{
    public string Id { get; set; } = "";
    public string CustomerId { get; set; } = "";
    public DateTime CreatedAtUtc { get; set; }
    public double Total { get; set; }
    public string Status { get; set; } = "";
    public List<OrderLine> Lines { get; set; } = [];
}
class OrderLine
{
    public int Id { get; set; }
    public string OrderId { get; set; } = "";
    public string Sku { get; set; } = "";
    public int Quantity { get; set; }
    public double UnitPrice { get; set; }
}
class Notification
{
    public int Id { get; set; }
    public string OrderId { get; set; } = "";
    public string Channel { get; set; } = "";
    public DateTime CreatedAtUtc { get; set; }
}

class ShopDb(DbContextOptions<ShopDb> options) : DbContext(options)
{
    public DbSet<Customer> Customers => Set<Customer>();
    public DbSet<Product> Products => Set<Product>();
    public DbSet<Order> Orders => Set<Order>();
    public DbSet<OrderLine> OrderLines => Set<OrderLine>();
    public DbSet<Notification> Notifications => Set<Notification>();

    protected override void OnModelCreating(ModelBuilder b)
    {
        b.Entity<Customer>().ToTable("customers").HasKey(x => x.Id);
        b.Entity<Product>().ToTable("products").HasKey(x => x.Sku);
        var o = b.Entity<Order>();
        o.ToTable("orders").HasKey(x => x.Id);
        o.HasIndex(x => new { x.CustomerId, x.CreatedAtUtc });
        o.HasMany(x => x.Lines).WithOne().HasForeignKey(l => l.OrderId);
        b.Entity<OrderLine>().ToTable("order_lines");
        b.Entity<Notification>().ToTable("notifications");
    }
}
